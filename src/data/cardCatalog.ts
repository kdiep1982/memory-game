/**
 * Get card pairs by category
 */
export function getCardsByCategory(
  category: "animal" | "vehicle",
): CardPairDefinition[] {
  return CARD_CATALOG.filter((card) => card.category === category);
}

/**
 * Get a random selection of card pairs for a level
 */
export function selectRandomPairs(count: number): CardPairDefinition[] {
  if (count > CARD_CATALOG.length) {
    throw new Error(
      `Cannot select ${count} pairs, only ${CARD_CATALOG.length} available`,
    );
  }

  const shuffled = [...CARD_CATALOG].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}

/**
 * Validate catalog integrity
 */
export function validateCatalog(): { valid: boolean; errors: string[] } {
  const errors: string[] = [];

  if (CARD_CATALOG.length !== 40) {
    errors.push(`Expected 40 pairs, found ${CARD_CATALOG.length}`);
  }

  const animals = getCardsByCategory("animal");
  const vehicles = getCardsByCategory("vehicle");

  if (animals.length !== 20) {
    errors.push(`Expected 20 animals, found ${animals.length}`);
  }

  if (vehicles.length !== 20) {
    errors.push(`Expected 20 vehicles, found ${vehicles.length}`);
  }

  const uniquePairIds = new Set(CARD_CATALOG.map((c) => c.pairId));
  if (uniquePairIds.size !== CARD_CATALOG.length) {
    errors.push("Duplicate pairId values found");
  }

  return {
    valid: errors.length === 0,
    errors,
  };
}
